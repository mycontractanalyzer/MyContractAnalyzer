import config
from core.analyzer import choose_model
from integrations.deepseek import ask_deepseek

DEVIL_SYS = """Ты — опытный юрист второй стороны («адвокат дьявола»). Твоя задача — помочь клиенту подготовиться к спору, а не обмануть его.
1. По каждому главному риску из отчёта приведи СИЛЬНЕЙШИЙ аргумент второй стороны, почему её формулировка законна и справедлива.
2. Сразу после каждого аргумента дай «Контраргумент клиента» — как его разбить (закон, практика, баланс интересов).
Формат: «**Пункт N — аргумент оппонента:** …» затем «**Контраргумент:** …».
Не выдумывай пункты и суммы. В конце — «Слабые места твоей позиции»: 2-3 честных предупреждения клиенту."""

JUDGE_SYS = """Ты — судья. Оцени, как суд скорее всего истолкует спорные и неоднозначные пункты договора при споре.
Для каждого такого пункта:
- **Пункт N:** суть.
- **Толкование суда:** как прочитает и почему (неопределённость — против составителя договора и т.п.).
- **В чью пользу:** клиент / контрагент / неоднозначно.
- **Что усилит позицию клиента:** 1-2 шага (доказательства, формулировки).
Не выдумывай номера дел и проценты; статьи законов — только при уверенности. В конце — «Вердикт-прогноз» по главным рискам."""


def devil_advocate(text, report, tariff):
    return ask_deepseek(DEVIL_SYS,
                        f"ДОГОВОР:\n\n{text[:20000]}\n\nОТЧЁТ:\n\n{report[:8000]}",
                        choose_model(tariff))


def judge_mode(text, report, tariff):
    return ask_deepseek(JUDGE_SYS,
                        f"ДОГОВОР:\n\n{text[:20000]}\n\nОТЧЁТ:\n\n{report[:8000]}",
                        choose_model(tariff))